-- Store the latest observed freshness state per deployed task and sparse state transitions.
CREATE TABLE public.edge_task_freshness_current (
    edge_id text NOT NULL REFERENCES public.platform_edges(edge_id) ON DELETE CASCADE,
    configuration_key text NOT NULL,
    state text NOT NULL,
    threshold_ms integer,
    state_since timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT pk_edge_task_freshness_current PRIMARY KEY (edge_id, configuration_key),
    CONSTRAINT ck_edge_task_freshness_current_state
        CHECK (state IN ('unknown', 'unmonitored', 'within-limit', 'timeout', 'removed'))
);

CREATE TABLE public.edge_task_freshness_transitions (
    transition_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edge_id text NOT NULL REFERENCES public.platform_edges(edge_id) ON DELETE CASCADE,
    configuration_key text NOT NULL,
    previous_state text,
    state text NOT NULL,
    threshold_ms integer,
    effective_at timestamp with time zone NOT NULL,
    detected_at timestamp with time zone NOT NULL,
    duration_ms bigint,
    last_valid_snapshot_at timestamp with time zone,
    CONSTRAINT ck_edge_task_freshness_transitions_state
        CHECK (state IN ('unknown', 'unmonitored', 'within-limit', 'timeout', 'removed'))
);

CREATE INDEX idx_edge_task_freshness_transitions_edge_detected
    ON public.edge_task_freshness_transitions(edge_id, detected_at DESC);

CREATE INDEX idx_edge_task_freshness_transitions_detected
    ON public.edge_task_freshness_transitions(detected_at);

CREATE INDEX idx_edge_runtime_status_history_recorded_at
    ON public.edge_runtime_status_history(recorded_at);
