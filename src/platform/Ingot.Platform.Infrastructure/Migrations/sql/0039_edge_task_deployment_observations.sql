-- Preserve bounded Platform observations of Edge-reported applied task versions for run-quality review.
-- Keep the original Edge report timestamp for diagnostics, including reports rejected by the freshness guard.
ALTER TABLE public.edge_runtime_status_history
    ADD COLUMN acquisition_reported_at timestamp with time zone;

CREATE TABLE public.edge_task_deployment_observations (
    observation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edge_id text NOT NULL REFERENCES public.platform_edges(edge_id) ON DELETE CASCADE,
    task_id text NOT NULL,
    task_version integer NOT NULL,
    configuration_hash text NOT NULL,
    configuration_source text NOT NULL,
    first_observed_at timestamp with time zone NOT NULL,
    last_observed_at timestamp with time zone NOT NULL,
    closed_observed_at timestamp with time zone,
    first_edge_reported_at timestamp with time zone,
    last_edge_reported_at timestamp with time zone,
    edge_applied_at_hint timestamp with time zone,
    last_deployment_state text,
    CONSTRAINT ck_edge_task_deployment_observations_version CHECK (task_version > 0),
    CONSTRAINT ck_edge_task_deployment_observations_source CHECK (configuration_source IN ('platform', 'cache')),
    CONSTRAINT ck_edge_task_deployment_observations_order CHECK (first_observed_at <= last_observed_at),
    CONSTRAINT ck_edge_task_deployment_observations_closed_order
        CHECK (closed_observed_at IS NULL OR closed_observed_at >= last_observed_at)
);

-- One current observed identity is maintained per task and Edge; reappearance creates a new segment.
CREATE UNIQUE INDEX ux_edge_task_deployment_observations_active
    ON public.edge_task_deployment_observations(edge_id, task_id)
    WHERE closed_observed_at IS NULL;

CREATE INDEX idx_edge_task_deployment_observations_edge_period
    ON public.edge_task_deployment_observations(edge_id, first_observed_at, last_observed_at);

CREATE INDEX idx_edge_task_deployment_observations_task_version
    ON public.edge_task_deployment_observations(task_id, task_version, edge_id);

-- Retain a per-Edge event-time watermark so a delayed fresh-looking report cannot reopen older applied state.
CREATE TABLE public.edge_task_deployment_observation_state (
    edge_id text PRIMARY KEY REFERENCES public.platform_edges(edge_id) ON DELETE CASCADE,
    last_trusted_edge_reported_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);
